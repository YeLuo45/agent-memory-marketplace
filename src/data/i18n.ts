export const t = (key: string, locale: Locale = 'en', vars: Record<string, unknown> | undefined = undefined): string => {
  const localeStrs = STRINGS[locale] ?? STRINGS.en;
  const tmpl = localeStrs[key] ?? STRINGS.en[key] ?? key;
  if (!vars) return tmpl;
  return Object.entries(vars).reduce(
    (acc, [k, v]) => acc.replaceAll(`{${k}}`, String(v)),
    tmpl,
  );
};

