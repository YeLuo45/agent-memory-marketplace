// 4-tier locale fallback helper. Pass the current locale + en + zh + ja + ko; returns the
// first non-empty value in priority order [requested locale → en (always available)].
// In practice: ja request → ja → ko → zh → en. ko request → ko → ja → zh → en.
// zh request → zh → ja → ko → en. en request → en.
export const pickI18n = <T,>(locale: Locale, en: T, zh?: T | null, ja?: T | null, ko?: T | null): T => {
  if (locale === 'ja') return (ja ?? ko ?? zh ?? en) as T;
  if (locale === 'ko') return (ko ?? ja ?? zh ?? en) as T;
  if (locale === 'zh') return (zh ?? ja ?? ko ?? en) as T;
  return en;
};

// Generic "first non-empty" helper used for en→zh→ja→ko cascade when locale is unknown.
// Iterates the *rest* args (zh, ja, ko, …) only — en is the fallback, never returned
// unless ALL rest args are empty. This matches the typical "give me a localized variant
// if any was provided, else fall back to English" call site.
export const firstI18n = <T,>(en: T, ...rest: Array<T | undefined | null>): T => {
  for (const v of rest) {
    if (v !== undefined && v !== null && v !== '') return v;
  }
  return en;
};
